void draw_sleep_screen(lv_obj_t *canvas) {
    lv_draw_img_dsc_t img_dsc;
    lv_draw_img_dsc_init(&img_dsc);
    // The cloud sits above Franklin, its trailing bubbles pointing down at his
    // ear. The two images are stacked, not overlapping: a 1-bit indexed image
    // paints its index-0 pixels too, so a later draw would erase an earlier one.
    // Together they are 132px tall, centred on the 168px screen: (168-132)/2 = 18.
    lv_canvas_draw_img(canvas, 24, 18, &dream_cloud, &img_dsc);
    // 136px wide on a 144px screen: (144-136)/2 = 4
    lv_canvas_draw_img(canvas, 4, 74, &sleep_icon, &img_dsc);
}
